/**
 * Builds the Vercel serverless function bundle: `api/index.js` (ESM).
 *
 * Why a bundle? Vercel's Node runtime executes the function from an isolated
 * directory where the TypeScript sources (`server.ts`) are not available, and
 * ESM cannot resolve extensionless specifiers. Bundling produces one
 * self-contained ESM module that default-exports the Express app.
 *
 * Usage: node scripts/build-api.mjs
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

await build({
  entryPoints: [path.join(root, 'scripts/serverless-entry.ts')],
  outfile: path.join(root, 'api/index.js'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  sourcemap: false,
  logLevel: 'warning',
  // Vite is only used by the long-running dev/prod server, never serverless.
  external: ['vite'],
  banner: {
    js: [
      '// Generated by scripts/build-api.mjs from server.ts — do not edit by hand.',
      // Bundled CommonJS dependencies (express, body-parser, ...) call require()
      // for Node builtins, which is unavailable in ESM without this shim.
      "import { createRequire as __cpCreateRequire } from 'node:module';",
      'const require = __cpCreateRequire(import.meta.url);',
    ].join('\n'),
  },
});

console.log('[build-api] api/index.js generated from server.ts');
